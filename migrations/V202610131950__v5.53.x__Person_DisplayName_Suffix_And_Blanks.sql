-- Description: Redefine the PERSISTED computed column Person.DisplayName (the People
--              name field, V202605131929) to skip blank parts and to carry Suffix:
--                FirstName + ' ' + LastName   ->   "John Smith Jr."
--
-- WHY. FirstName and LastName are NOT NULL but may be blank, so the old expression
-- produced " Smith", "Madonna " or a lone space. Suffix is part of the name: "John Smith
-- Jr." and "John Smith Sr." are different people and looked identical everywhere the
-- name field shows (pickers, FK labels such as Relationship.FromPerson, record names).
--
-- WHY NOT EMAIL OR ORGANIZATION. The name field is the person's label in every place
-- that names them; email there spreads personal data, and the employer is a Relationship
-- (it changes, and a PERSISTED column cannot read it). Pickers that need to tell two
-- people apart use vwPeople's PrimaryEmail / CurrentOrganizationName instead.
--
-- SHAPE. CONCAT_WS(N' ', ...) over NULLIF(TRIM(x), N'') parts: blank parts are dropped,
-- so a name never has leading, trailing or double spaces. All-blank gives N'' (never
-- NULL). NVARCHAR(250) holds FirstName (100) + LastName (100) + Suffix (20) + two spaces.
-- The outer ISNULL(..., N'') is not redundant: the column is NOT NULL either way, but a
-- view over a computed column takes its nullability from the expression, and SQL Server
-- types CAST(CONCAT_WS(...)) as nullable. Without ISNULL, vwPeople.DisplayName (and every
-- FK label joined from it, e.g. Relationship.FromPerson) would turn nullable and CodeGen
-- would retype PersonEntity.DisplayName from string to string | null.
--
-- HOW. A computed column's expression cannot be altered in place: drop its index, drop
-- the column, add it back with the new expression, recreate the index (same name and
-- shape as V202609290300). No view is schema-bound to it. Guarded on the current
-- definition, so a database that already has the new shape is left alone.
--
-- POSTGRESQL. Release work. concat_ws() is STABLE, not IMMUTABLE, so the GENERATED column
-- needs || with COALESCE/NULLIF instead.
-- =============================================================================

