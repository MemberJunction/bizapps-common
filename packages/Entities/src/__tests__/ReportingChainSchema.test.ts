/**
 * Schema, migration, SQL, and TypeScript contract verification for Slice 1:
 *  - People.SupervisorPersonID (nullable self-referential FK to Person.ID + FK index)
 *  - Cycle-safe recursive view vwPersonReportingChain (PersonID, SupervisorPersonID, Depth)
 *  - Atomic SyncEmployeesToPeople routine syncing SupervisorPersonID & dated 'Reports To' rows
 *  - Dual-dialect parity between SQL Server (migrations/) and PostgreSQL (migrations-pg/)
 *  - Strongly-typed Person entity/schema properties & reporting-chain metadata
 */
import { readdirSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import {
    PERSON_REPORTING_CHAIN_VIEW,
    REPORTS_TO_RELATIONSHIP_TYPE,
    REPORTS_TO_RELATIONSHIP_TYPE_ID,
    SYNC_EMPLOYEES_TO_PEOPLE_PROCEDURE,
    mjBizAppsCommonPersonEntity,
    mjBizAppsCommonPersonSchema,
    type PersonReportingChainRow,
    type mjBizAppsCommonPersonEntityType,
} from '../index.js';

const MIGRATIONS_DIR = fileURLToPath(new URL('../../../../migrations/', import.meta.url));
const MIGRATIONS_PG_DIR = fileURLToPath(new URL('../../../../migrations-pg/', import.meta.url));
const RELATIONSHIP_TYPES_PATH = fileURLToPath(
    new URL('../../../../metadata/relationship-types/.relationship-types.json', import.meta.url),
);

function findLatestMigration(dir: string, pattern: RegExp): string {
    const match = readdirSync(dir)
        .filter((f) => pattern.test(f))
        .sort()
        .pop();
    if (!match) {
        throw new Error(`No migration matching ${pattern} in ${dir}`);
    }
    return match;
}

const tsSqlFile = findLatestMigration(MIGRATIONS_DIR, /__Person_Supervisor_Reporting_Chain\.sql$/);
const tsSqlRaw = readFileSync(MIGRATIONS_DIR + tsSqlFile, 'utf8');
const tsSqlParts = tsSqlRaw.split(
    /-- =============================================================================\r?\n-- GENERATED BY MemberJunction CodeGen/,
);
const tsHandWritten = tsSqlParts[0] ?? '';
const tsCodeGen = tsSqlParts[1] ?? '';
const tsFlat = tsSqlRaw.replace(/\s+/g, ' ');
const tsHandFlat = tsHandWritten.replace(/\s+/g, ' ');

const pgSqlFile = findLatestMigration(MIGRATIONS_PG_DIR, /__Person_Supervisor_Reporting_Chain\.pg\.sql$/);
const pgSqlRaw = readFileSync(MIGRATIONS_PG_DIR + pgSqlFile, 'utf8');
const pgFlat = pgSqlRaw.replace(/\s+/g, ' ');

describe('Slice 1: Supervisor Hierarchy, vwPersonReportingChain, and SyncEmployeesToPeople', () => {
    it('ships paired SQL Server and PostgreSQL migrations at the exact same version stamp', () => {
        expect(pgSqlFile.replace(/\.pg\.sql$/, '.sql')).toBe(tsSqlFile);
    });

    it('separates hand-written DDL from CodeGen block with at least 50 blank lines in T-SQL migration', () => {
        expect(tsSqlParts.length).toBe(2);
        const trailingBlankLines = tsHandWritten.match(/\n+$/);
        const newlineCount = trailingBlankLines ? trailingBlankLines[0].length - 1 : 0;
        expect(newlineCount).toBeGreaterThanOrEqual(50);
    });

    it('keeps hand-written T-SQL DDL free of existence guards', () => {
        expect(tsHandFlat).not.toMatch(/\bIF (OBJECT_ID|COL_LENGTH)\(/i);
        expect(tsHandFlat).not.toMatch(/\bIF NOT EXISTS\b/i);
    });

    describe('SQL Server migration (T-SQL)', () => {
        it('adds nullable Person.SupervisorPersonID with self-referential FK, CodeGen FK index, and MS_Description', () => {
            expect(tsHandFlat).toContain(
                'ALTER TABLE [${flyway:defaultSchema}].[Person] ADD [SupervisorPersonID] UNIQUEIDENTIFIER NULL;',
            );
            expect(tsHandFlat).toContain(
                'ADD CONSTRAINT [FK_Person_SupervisorPerson] FOREIGN KEY ([SupervisorPersonID]) REFERENCES [${flyway:defaultSchema}].[Person]([ID]);',
            );
            expect(tsHandFlat).toContain(
                'CREATE NONCLUSTERED INDEX [IDX_AUTO_MJ_FKEY_Person_SupervisorPersonID] ON [${flyway:defaultSchema}].[Person] ([SupervisorPersonID]);',
            );
            expect(tsHandFlat).toContain("@level2name = N'SupervisorPersonID'");
        });

        it('defines recursive vwPersonReportingChain exposing (PersonID, SupervisorPersonID, Depth) with path-based cycle protection', () => {
            expect(tsHandFlat).toContain('CREATE OR ALTER VIEW [${flyway:defaultSchema}].[vwPersonReportingChain]');
            expect(tsHandFlat).toContain('WITH [ReportingChain] AS');
            expect(tsHandFlat).toContain('p.[SupervisorPersonID] <> p.[ID]');
            expect(tsHandFlat).toContain('UNION ALL');
            expect(tsHandFlat).toContain('CHARINDEX');
            expect(tsHandFlat).toContain('[VisitedPath]');
            expect(tsHandFlat).toContain('rc.[Depth] < 100');
            expect(tsHandFlat).toContain('SELECT [PersonID], [SupervisorPersonID], [Depth] FROM [ReportingChain]');
            expect(tsHandFlat).toContain(
                'GRANT SELECT ON [${flyway:defaultSchema}].[vwPersonReportingChain] TO [cdp_UI], [cdp_Developer], [cdp_Integration]',
            );
        });

        it('defines atomic SyncEmployeesToPeople populating SupervisorPersonID and maintaining dated Reports To relationships', () => {
            expect(tsHandFlat).toContain('CREATE OR ALTER PROCEDURE [${flyway:defaultSchema}].[SyncEmployeesToPeople]');
            expect(tsHandFlat).toContain('SET XACT_ABORT ON;');
            expect(tsHandFlat).toContain('BEGIN TRANSACTION;');
            expect(tsHandFlat).toContain('COMMIT TRANSACTION;');
            expect(tsHandFlat).toContain('ROLLBACK TRANSACTION;');
            expect(tsHandFlat).toContain('THROW;');
            expect(tsHandFlat).toContain("N'reports to'");
            expect(tsHandFlat).toContain('FROM [${mjSchema}].[Employee]');
            expect(tsHandFlat).toContain('SET p.[SupervisorPersonID] = s.[TargetSupervisorPersonID]');
            expect(tsHandFlat).toContain("SET r.[Status] = N'Ended', r.[EndDate] = COALESCE(r.[EndDate], @SyncDate)");
            expect(tsHandFlat).toContain("N'Active'");
            expect(tsHandFlat).toContain('[StartDate]');
            expect(tsHandFlat).toContain(
                'GRANT EXECUTE ON [${flyway:defaultSchema}].[SyncEmployeesToPeople] TO [cdp_Developer], [cdp_Integration]',
            );
        });

        it('updates EntityField metadata (dynamic Sequence), vwPeopleGenerated, spCreatePerson, spUpdatePerson, and People FLS permissions', () => {
            expect(tsCodeGen).toContain("Name = 'SupervisorPersonID'");
            expect(tsCodeGen).toContain("Name = 'SupervisorPerson'");
            expect(tsCodeGen).toContain('COALESCE(MAX([Sequence]), 0) + 1');
            expect(tsCodeGen).toContain('vwPeopleGenerated');
            expect(tsCodeGen).toContain('spCreatePerson');
            expect(tsCodeGen).toContain('spUpdatePerson');
            expect(tsCodeGen).toContain('@SupervisorPersonID uniqueidentifier = NULL');
            expect(tsFlat).toContain('INSERT INTO [${mjSchema}].[EntityFieldPermission]');
        });
    });

    describe('PostgreSQL migration (.pg.sql)', () => {
        it('uses lowercase unquoted __mj_bizappscommon schema and never emits mixed-case quoted schema identifiers', () => {
            expect(pgFlat).toContain('CREATE SCHEMA IF NOT EXISTS __mj_bizappscommon;');
            expect(pgFlat).not.toContain('"__mj_BizAppsCommon"');
            expect(pgFlat).not.toMatch(/"__mj_bizappscommon"[.]/i);
        });

        it('adds nullable Person."SupervisorPersonID" UUID with self-referential FK, index, and column comment', () => {
            expect(pgFlat).toContain('ALTER TABLE __mj_bizappscommon."Person" ADD COLUMN "SupervisorPersonID" UUID NULL;');
            expect(pgFlat).toContain(
                'ADD CONSTRAINT "FK_Person_SupervisorPerson" FOREIGN KEY ("SupervisorPersonID") REFERENCES __mj_bizappscommon."Person"("ID");',
            );
            expect(pgFlat).toContain(
                'CREATE INDEX IF NOT EXISTS "IDX_AUTO_MJ_FKEY_Person_SupervisorPersonID" ON __mj_bizappscommon."Person" ("SupervisorPersonID");',
            );
            expect(pgFlat).toContain('COMMENT ON COLUMN __mj_bizappscommon."Person"."SupervisorPersonID"');
        });

        it('defines recursive vwPersonReportingChain with WITH RECURSIVE and VisitedPath array cycle guard', () => {
            expect(pgFlat).toContain('CREATE OR REPLACE VIEW __mj_bizappscommon."vwPersonReportingChain"');
            expect(pgFlat).toContain('WITH RECURSIVE "ReportingChain" ("PersonID", "SupervisorPersonID", "Depth", "VisitedPath")');
            expect(pgFlat).toContain('ARRAY[p."ID", p."SupervisorPersonID"]');
            expect(pgFlat).toContain('NOT (sup."SupervisorPersonID" = ANY(rc."VisitedPath"))');
            expect(pgFlat).toContain('rc."Depth" < 100');
            expect(pgFlat).toContain('SELECT "PersonID", "SupervisorPersonID", "Depth" FROM "ReportingChain"');
        });

        it('defines SyncEmployeesToPeople procedure in PostgreSQL synchronizing SupervisorPersonID and dated Reports To relationships', () => {
            expect(pgFlat).toContain('CREATE OR REPLACE PROCEDURE __mj_bizappscommon."SyncEmployeesToPeople"()');
            expect(pgFlat).toContain('FROM ${mjSchema}."Employee" AS emp');
            expect(pgFlat).toContain('SET "SupervisorPersonID" = s."TargetSupervisorPersonID"');
            expect(pgFlat).toContain('IS DISTINCT FROM s."TargetSupervisorPersonID"');
            expect(pgFlat).toContain('SET "Status" = \'Ended\', "EndDate" = COALESCE(r."EndDate", v_sync_date)');
            expect(pgFlat).toContain('\'Active\'');
            expect(pgFlat).toContain('"StartDate"');
            expect(pgFlat).toContain('INSERT INTO ${mjSchema}."EntityFieldPermission"');
        });
    });

    describe('TypeScript entity/schema types and metadata', () => {
        it('exposes SupervisorPersonID and SupervisorPerson on mjBizAppsCommonPersonSchema and mjBizAppsCommonPersonEntity', () => {
            expect(mjBizAppsCommonPersonSchema.shape.SupervisorPersonID).toBeDefined();
            expect(mjBizAppsCommonPersonSchema.shape.SupervisorPerson).toBeDefined();

            const proto = mjBizAppsCommonPersonEntity.prototype;
            const supervisorDescriptor = Object.getOwnPropertyDescriptor(proto, 'SupervisorPersonID');
            expect(supervisorDescriptor?.get).toBeTypeOf('function');
            expect(supervisorDescriptor?.set).toBeTypeOf('function');

            const supervisorNameDescriptor = Object.getOwnPropertyDescriptor(proto, 'SupervisorPerson');
            expect(supervisorNameDescriptor?.get).toBeTypeOf('function');

            // Compile-time type check ensuring SupervisorPersonID is typed as string | null on Person
            type SupervisorField = mjBizAppsCommonPersonEntityType['SupervisorPersonID'];
            const sampleSupervisor: SupervisorField = null;
            expect(sampleSupervisor).toBeNull();
        });

        it('exports strongly-typed PersonReportingChainRow and schema constants', () => {
            expect(PERSON_REPORTING_CHAIN_VIEW).toBe('vwPersonReportingChain');
            expect(REPORTS_TO_RELATIONSHIP_TYPE).toBe('Reports To');
            expect(SYNC_EMPLOYEES_TO_PEOPLE_PROCEDURE).toBe('SyncEmployeesToPeople');

            const row: PersonReportingChainRow = {
                PersonID: '11111111-1111-4111-8111-111111111111',
                SupervisorPersonID: '22222222-2222-4222-8222-222222222222',
                Depth: 1,
            };
            expect(row.Depth).toBe(1);
        });

        it('seeds the directional Reports To relationship type in metadata/relationship-types', () => {
            const raw = readFileSync(RELATIONSHIP_TYPES_PATH, 'utf8');
            const parsed = JSON.parse(raw) as Array<{
                fields: { Name: string; Category: string; IsDirectional: boolean; ForwardLabel: string; ReverseLabel: string };
                primaryKey: { ID: string };
            }>;
            const reportsTo = parsed.find((entry) => entry.fields.Name === REPORTS_TO_RELATIONSHIP_TYPE);
            expect(reportsTo).toBeDefined();
            expect(reportsTo?.primaryKey.ID).toBe(REPORTS_TO_RELATIONSHIP_TYPE_ID);
            expect(reportsTo?.fields.Category).toBe('PersonToPerson');
            expect(reportsTo?.fields.IsDirectional).toBe(true);
            expect(reportsTo?.fields.ForwardLabel).toBe('reports to');
            expect(reportsTo?.fields.ReverseLabel).toBe('supervises');
        });
    });
});
