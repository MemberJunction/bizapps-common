function findLatestMigration(dir: string, pattern: RegExp): string {
    const match = readdirSync(dir)
        .filter((f) => pattern.test(f))
        .sort()
        .pop();
    if (!match) {
        throw new Error(`No migration matching ${pattern} in ${dir}`);
    }
    return match;
}

