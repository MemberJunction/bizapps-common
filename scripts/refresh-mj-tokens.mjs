#!/usr/bin/env node
/**
 * Rewrites `scripts/mj-tokens.json`, the `--mj-*` names `check-mj-tokens.mjs` accepts.
 *
 * The tokens are defined in MemberJunction's `_tokens.scss`, which the Explorer host loads. No package
 * this repo installs ships that file, so the names are copied here from the MJ release this repo
 * floors at. Run it whenever the `@memberjunction/core` floor in packages/Angular is raised:
 *
 *     node scripts/refresh-mj-tokens.mjs                         # fetches _tokens.scss at tag v<floor>
 *     node scripts/refresh-mj-tokens.mjs <path/_tokens.scss>     # reads a local copy instead
 *
 * Ported from bizapps-sales `scripts/refresh-mj-tokens.mjs`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { mjFloor } from './check-mj-tokens.mjs';

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(REPO_ROOT, 'scripts/mj-tokens.json');
const TOKENS_PATH = 'packages/Angular/Generic/shared/src/lib/_tokens.scss';

async function readTokensSource(version, localPath) {
    if (localPath) return readFileSync(localPath, 'utf8');
    const url = `https://raw.githubusercontent.com/MemberJunction/MJ/v${version}/${TOKENS_PATH}`;
    const response = await fetch(url);
    if (!response.ok) throw new Error(`GET ${url} returned ${response.status}`);
    return response.text();
}

function extractTokenNames(source) {
    const names = new Set();
    for (const match of source.matchAll(/^\s*(--mj-[a-z0-9-]+)\s*:/gm)) names.add(match[1]);
    return [...names].sort();
}

const pkg = JSON.parse(readFileSync(join(REPO_ROOT, 'packages/Angular/package.json'), 'utf8'));
const version = mjFloor(pkg.devDependencies?.['@memberjunction/core']);
const tokens = extractTokenNames(await readTokensSource(version, process.argv[2]));
if (tokens.length === 0) {
    console.error('refresh-mj-tokens: ERROR — no --mj-* definitions found; refusing to write an empty list.');
    process.exit(2);
}
const body = {
    _comment: `Generated by scripts/refresh-mj-tokens.mjs from MemberJunction's ${TOKENS_PATH}. Do not edit by hand.`,
    mjVersion: version,
    tokens,
};
writeFileSync(OUT, JSON.stringify(body, null, 2) + '\n');
console.log(`refresh-mj-tokens: wrote ${tokens.length} token(s) from MJ v${version} to scripts/mj-tokens.json.`);
